def grade(total):
    if total < 25:
        return LOW
    if total < 50:
        return MEDIUM
    return HIGH


def assess(rates):
    """항목별 수행률(0~1, 없으면 0)로 잔여 위험·등급을 계산한다."""
    for item, rate in rates.items():
        if item not in POINTS:
            raise ValueError(f"평가 항목이 아닙니다: {item}")
        if not 0 <= rate <= 1:
            raise ValueError(f"수행률은 0~1 사이여야 합니다: {item}={rate}")
    rows, by_principle = [], {}
    for i in ITEMS:
        rate = rates.get(i["item"], 0.0)
        residual = i["points"] * (1 - rate)
        rows.append({**i, "rate": rate, "residual": residual})
        by_principle[i["principle"]] = by_principle.get(i["principle"], 0) + residual
    total = sum(r["residual"] for r in rows)
    return {
        "items": rows,
        "by_principle": by_principle,
        "total": total,
        "grade": grade(total),
        "committee_review": total >= COMMITTEE_THRESHOLD,
    }


def required_controls(level):
    order = [LOW, MEDIUM, HIGH]
    return [c for lv in order[: order.index(level) + 1] for c in CONTROLS[lv]]


def report_markdown(name, result, evidence):
    lines = [
        f"# AI 위험평가 보고서 — {name}",
        "",
        f"- 총 잔여 위험: **{result['total']:.1f}점 / 100점 → {result['grade']}**",
        f"- AI 의사결정기구 재검토 대상(75점 이상): {'예' if result['committee_review'] else '아니오'}",
        "- 기준: 금융분야 인공지능 가이드라인(2026.6) 위험평가 예시표. 수행률은 평가자 판단이며 근거를 함께 적는다.",
        "",
        "## 원칙별 잔여 위험",
        "",
        "| 원칙 | 잔여 위험 |",
        "|---|---|",
    ]
    lines += [f"| {p} | {v:.1f} |" for p, v in result["by_principle"].items()]
    lines += ["", "## 항목별 평가", "", "| 원칙 | 항목 | 배점 | 수행률 | 잔여 위험 | 근거 |", "|---|---|---|---|---|---|"]
    lines += [
        f"| {r['principle']} | {r['item']} | {r['points']} | {r['rate']:.0%} | {r['residual']:.1f} | {evidence.get(r['item'], '')} |"
        for r in result["items"]
    ]
    lines += ["", f"## 필요 통제 ({result['grade']})", "", "| 통제 | 이 시스템의 구현 |", "|---|---|"]
    lines += [f"| {c} | {IMPLEMENTED[c]} |" for c in required_controls(result["grade"])]
    return "\n".join(lines) + "\n"
